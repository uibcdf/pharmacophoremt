/** Opt-in PHMT scenario through real Jupyter widget comms; no test transport shim. */
import { pathToFileURL } from 'node:url';
import fs from 'node:fs';
import assert from 'node:assert/strict';
const base=process.env.PHMT_BROWSER_WORKSPACE;
const helper=process.env.PHMT_BROWSER_HELPER;
assert.ok(base && helper, 'Set PHMT_BROWSER_WORKSPACE and PHMT_BROWSER_HELPER');
const { chromium }=await import(pathToFileURL(helper).href);
const notebook=process.env.PHMT_BROWSER_NOTEBOOK || 'addon.ipynb';
assert.ok(/^[a-zA-Z0-9_-]+\.ipynb$/.test(notebook), 'Use a notebook basename');
const connection=JSON.parse(fs.readFileSync(base+'/connection.json','utf8'));
const browser=await chromium.launch();
const page=await browser.newPage({viewport:{width:1440,height:1050}});
const errors=[];
const consoleMessages=[];
const results=[];
page.on('pageerror',e=>errors.push(String(e)));
page.on('console',m=>consoleMessages.push({type:m.type(),text:m.text().replace(/token=[A-Za-z0-9_-]+/g,'token=<redacted>')}));
let sequence=0;
async function cell(code, expression){
 const marker='PHMT_CONTROL_'+(++sequence)+':';
 const editor=page.locator('.jp-Notebook .jp-CodeCell .cm-content').last();
 await editor.click();
 await editor.fill(code+`\nimport json\nprint('${marker}' + json.dumps(${expression}, default=str))`);
 await page.keyboard.press('Shift+Enter');
 const output=page.locator('.jp-OutputArea-output').filter({hasText:marker});
 await output.waitFor({timeout:30000});
 const text=await output.innerText();
 return JSON.parse(text.split(marker).at(-1).split('\n')[0]);
}
const stateExpr="{'tags': view.shapes.tags(), 'owned': list(runtime.rendered_tags), 'events': list(runtime.event_log), 'records': view.shapes.records(), 'panel_mode': view.get_panel_mode_state()}";
async function toggle(){
 const close=page.getByTitle('Close (Esc)',{exact:true});
 if(await close.isVisible()) await close.click();
 else await page.getByTitle('Panel mode (N / W)',{exact:true}).click();
}
async function remount(){
 await page.locator('[data-molsysviewer-addon-workspace-tab=core]').click();
 await page.locator('.pharmt-panel').waitFor({state:'detached'});
 await page.locator('[data-molsysviewer-addon-workspace-tab=pharmacophoremt]').click();
 await page.locator('.pharmt-panel').waitFor();
}
try{
 await page.goto(`http://127.0.0.1:${connection.port}/lab/workspaces/phmt-${Date.now()}/tree/${notebook}?token=${connection.token}`,{waitUntil:'domcontentloaded'});
 await page.locator('.jp-Notebook .jp-CodeCell').first().waitFor({timeout:60000});
 const newsNo=page.getByRole('button',{name:'No',exact:true});
 if(await newsNo.isVisible()) await newsNo.click();
 await page.locator('.jp-Notebook .jp-CodeCell .cm-content').first().click();
 await page.keyboard.press('Shift+Enter');
 await page.locator('canvas').first().waitFor({timeout:60000});
 await toggle();
 await page.getByRole('button',{name:'Add-ons',exact:true}).click();
 await page.locator('[data-molsysviewer-addon-workspace-tab=pharmacophoremt]').click();
 await page.locator('.pharmt-panel').waitFor({timeout:30000});
 await page.waitForFunction(()=>document.querySelector('#pharmt-summary')?.textContent?.toLowerCase().includes('hydrophobicity'));
 assert.equal(await page.locator('.pharmt-row').count(),2);
 assert.equal(await page.locator('#pharmt-render').isEnabled(),true);
 results.push({control:'initial summary',summary:await page.locator('#pharmt-summary').innerText()});
 await toggle();
 await cell('view.camera.reset()', stateExpr);
 await page.getByText('Switching to workspace: PharmacophoreMT',{exact:true}).waitFor({state:'hidden'});
 await page.locator('canvas').first().screenshot({path:base+'/baseline-canvas.png'});
 await toggle();
 await page.locator('#pharmt-render').click();
 await page.waitForFunction(()=>document.querySelector('#pharmt-status')?.textContent==='Rendered.');
 await page.screenshot({path:base+'/rendered-panel.png',fullPage:true});
 const first=await cell('',stateExpr);
 assert.deepEqual(first.tags.sort(),['pharmt-site:0','pharmt-site:1','unrelated-control']);
 assert.equal(first.events.filter((x)=>x.event==='panel_render_pharmacophore').length,1);
 results.push({control:'first render',...first});
 await toggle();
 await cell('view.camera.reset()', stateExpr);
 await page.getByText('Switching to workspace: PharmacophoreMT',{exact:true}).waitFor({state:'hidden'});
 await page.locator('canvas').first().screenshot({path:base+'/rendered-canvas.png'});
 await toggle();
 await page.locator('#pharmt-render').click();
 await page.waitForFunction(()=>document.querySelector('#pharmt-status')?.textContent==='Rendered.');
 const repeated=await cell('',stateExpr);
 assert.equal(repeated.tags.length,3);
 assert.equal(repeated.events.filter((x)=>x.event==='panel_render_pharmacophore').length,2);
 results.push({control:'repeated render replaces own shapes',...repeated});
 await remount();
 await page.waitForFunction(()=>document.querySelector('#pharmt-summary')?.textContent?.toLowerCase().includes('hydrophobicity'));
 assert.equal(await page.locator('.pharmt-panel').count(),1);
 await page.locator('#pharmt-clear').click();
 const cleared=await cell('',stateExpr);
 assert.deepEqual(cleared.tags,['unrelated-control']);
 assert.deepEqual(cleared.owned,[]);
 results.push({control:'remount and clear preserve unrelated shape',...cleared});
 await toggle();
 await cell('view.camera.reset()', stateExpr);
 await page.getByText('Switching to workspace: PharmacophoreMT',{exact:true}).waitFor({state:'hidden'});
 await page.locator('canvas').first().screenshot({path:base+'/cleared-canvas.png'});
 await toggle();
 await page.locator('#pharmt-render').click();
 await page.waitForFunction(()=>document.querySelector('#pharmt-status')?.textContent==='Rendered.');
 await cell('from pharmacophoremt.interaction_site import IncludedVolumePoint\nmodel.interaction_sites.append(IncludedVolumePoint(position="[0, 0, 0] nm"))\nmodel.n_interaction_sites = 3',stateExpr);
 await page.locator('#pharmt-render').click();
 await page.waitForFunction(()=>document.querySelector('#pharmt-status')?.textContent?.includes('sphere sites only'));
 const invalid=await cell('',stateExpr);
 assert.equal(invalid.tags.length,3);
 assert.equal(invalid.owned.length,2);
 results.push({control:'unsupported point rejected and error visible',error:await page.locator('#pharmt-status').innerText(),...invalid});
 await page.screenshot({path:base+'/unsupported-input.png',fullPage:true});
 await cell('model.interaction_sites.pop()\nmodel.n_interaction_sites = 2\noriginal_clear = view.shapes.clear\ndef reject_clear(*args, **kwargs):\n    raise RuntimeError("controlled provider clear failure")\nview.shapes.clear = reject_clear',stateExpr);
 await page.locator('#pharmt-clear').click();
 await page.waitForFunction(()=>document.querySelector('#pharmt-status')?.textContent?.includes('controlled provider clear failure'));
 const failedClear=await cell('',stateExpr);
 assert.equal(failedClear.owned.length,2);
 assert.equal(failedClear.tags.length,3);
 results.push({control:'provider clear failure is visible and retryable',error:await page.locator('#pharmt-status').innerText(),...failedClear});
 await cell('view.shapes.clear = original_clear',stateExpr);
 await page.locator('#pharmt-clear').click();
 const retry=await cell('',stateExpr);
 assert.deepEqual(retry.tags,['unrelated-control']);
 assert.deepEqual(retry.owned,[]);
 results.push({control:'clear retry succeeds',...retry});
 await cell('runtime.pharmacophore = Pharmacophore()',stateExpr);
 await remount();
 await page.waitForFunction(()=>document.querySelector('#pharmt-summary')?.textContent?.includes('No pharmacophore loaded.'));
 assert.equal(await page.locator('#pharmt-render').isDisabled(),true);
 results.push({control:'empty cached model disables render',summary:await page.locator('#pharmt-summary').innerText()});
 await cell('runtime.pharmacophore = model',stateExpr);
 await remount();
 await page.waitForFunction(()=>document.querySelector('#pharmt-summary')?.textContent?.toLowerCase().includes('hydrophobicity'));
 await page.locator('#pharmt-render').click();
 await page.waitForFunction(()=>document.querySelector('#pharmt-status')?.textContent==='Rendered.');
 const disabled=await cell('view.addons.disable("pharmacophoremt")',stateExpr);
 assert.deepEqual(disabled.tags,['unrelated-control']);
 assert.deepEqual(disabled.owned,[]);
 results.push({control:'disable clears own shapes',...disabled});
 assert.deepEqual(errors,[]);
 fs.writeFileSync(base+'/live-controls.json',JSON.stringify({status:'passed',browser:browser.version(),results,errors,consoleMessages},null,2));
 console.log(JSON.stringify({status:'passed',controls:results.length,browser:browser.version(),errors}));
}catch(error){
 await page.screenshot({path:base+'/controls-failure.png',fullPage:true});
 fs.writeFileSync(base+'/live-controls.json',JSON.stringify({status:'failed',error:String(error),results,errors,consoleMessages,text:await page.locator('body').innerText()},null,2));
 throw error;
}finally{await browser.close();}
